def get_yearly_health_template(year: int, all_major_events: list,
                              exercise_changes_timeline: list, 
                              health_status_timeline: list) -> str:
    """
    获取年度健康生活问题生成模板
    
    Args:
        year: 年份
        all_major_events: 全年各月主要事件时间线
        exercise_changes_timeline: 全年运动变化时间线
        health_status_timeline: 全年健康状况时间线
        
    Returns:
        格式化后的 Prompt
    """
    import json
    return f"""
    作为健康生活分析师，请基于以下{year}年全年的用户健康和运动变化数据，从全年视角分析用户的健康管理模式和生活方式质量，设计 3-5 个健康相关问题。
    
    【全年各月主要事件时间线】
    {json.dumps(all_major_events, ensure_ascii=False, indent=2)}
    
    【全年运动变化时间线】
    {json.dumps(exercise_changes_timeline, ensure_ascii=False, indent=2)}
    
    【全年健康状况时间线】
    {json.dumps(health_status_timeline, ensure_ascii=False, indent=2)}
    
    **任务要求**
    从全年视角出发，生成 3-5 个能够考察用户健康管理、运动习惯或生活方式的问题。
    问题应该：
    - 分析全年健康趋势和生活方式模式
    - 识别健康习惯的关键转折点和持续性
    - 探讨生活质量和工作生活平衡的年度变化
    - 引导反思健康意识和自我管理的成效
    
    请以 JSON 格式返回问题列表，每个问题包含：
    - question: 问题内容
    - answer: 预期答案（基于提供的全年数据给出具体回答）
    - analysis: 问题分析（说明基于什么设计该问题，需要回答者根据什么推理出答案）
    - question_type: "yearly_health_fitness"
    
    返回格式：
    [
        {{
            "question": "问题内容",
            "answer": "预期答案",
            "analysis": "问题分析：基于...设计，需要回答者根据...推理",
            "question_type": "yearly_health_fitness"
        }}
    ]
    """


def get_yearly_filter_template(questions: list, year: int) -> str:
    """
    获取年度问题过滤模板
    
    Args:
        questions: 待过滤的年度问题列表
        year: 年份
        
    Returns:
        格式化后的 Prompt
    """
    import json
    return f"""
    作为问题质量评估专家，请评估以下{year}年的年度模式识别问题，筛选出最有价值的问题。
    
    【问题列表】
    {json.dumps(questions, ensure_ascii=False, indent=2)}
    
    **评估标准**
    优质年度问题应该具备：
    1. 具有全年视角，能够总结年度变化和趋势
    2. 有深度，能引发对全年生活的深入反思
    3. 能够识别年度关键转折点和重要变化
    4. 问题清晰明确，不模糊笼统
    5. 避免重复或过于简单的问题
    6. **【强制检查】题目必须明确包含具体月份或年份**：如"5月"、"6月"或"2025年"，不能模糊如"这个月"、"上个月"。如果问题未明确写出月份或年份，该问题判定为不合格并过滤掉。
    
    **任务要求**
    从以上列表中筛选出符合标准的问题，最多保留 12 个高质量年度问题。
    
    请以 JSON 格式返回筛选结果：
    {{
        "selected_indices": [0, 2, 3, 5],  // 选中问题的索引列表
        "reason": "筛选理由简述"
    }}
    """