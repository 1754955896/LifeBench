"""
模式识别 QA 生成器模板
包含所有用于生成模式识别与习惯分析问题的 Prompt 模板
"""


def get_preference_template(month_key: str, major_events: str, preference_changes: str, 
                           new_habits: list, changed_habits: list) -> str:
    """
    获取习惯与偏好类问题生成模板
    
    Args:
        month_key: 月份标识
        major_events: 主要事件总结
        preference_changes: 偏好和习惯变化
        new_habits: 新养成的习惯列表
        changed_habits: 发生改变的习惯列表
        
    Returns:
        格式化后的 Prompt
    """
    return f"""
    作为用户的智能生活助手，请基于以下{month_key}的用户生活记录数据，生成 2-3 个用户可能会问的习惯与偏好相关问题。
    
    场景设定 你需要模拟用户对一款记录了用户一年手机数据的手机智能助手设计问题提问。你需要设计问题， 而你用户助手需要整合分析记录的数据并推理来回答这些问题。
    **题目设计要求**
    1. **问题叙述合理真实**：使用第一人称"我"，问题自然、符合真实用户的提问习惯
    2. **信息适度原则**：问题只包含回答所需的基本信息，不要透露过多细节
       -  错误示例："5月看了很多心理学的书，接下来该看什么？"（预设了具体内容）
       -  正确示例："对于我5月时候的兴趣，你推荐我学习数据分析还是机器学习？"
    3. **数据依赖性**：问题必须通过查询和分析数据才能回答，不能仅凭题面直接推断
       -  错误示例："我对编程的兴趣增加了，能坚持下去吗？"（已知增加，可直接推理）
       -  正确示例："我6月下半月在英语学习上花的时间多吗？"（需查询具体数据）
    4. **整合性挑战**：设计需要综合分析多源数据的问题，增加回答难度
       - 需要结合学习内容、时间分配、兴趣变化等多维度信息进行推理
       - 需要从分散的数据中识别兴趣模式或学习趋势
       - 例如："我5月关注的领域和我4月学习的技能有关联吗？"（需要交叉分析关注和学习的记录）
    5. **【强制要求】题目中必须明确包含具体月份**：如"5月"、"6月"，不能模糊如"这个月"、"上个月"。如果问题未明确写出月份，该问题视为不合格。
    6. 题目中不要提及太多信息，不要设计可自然根据题面判断的问题，如："我4月练了普拉提，对我的健康有效果吗，适合继续练吗？"（在不看数据的情况下，都可以直接回答有效果，适合，因为这是常识，这会导致问题没有意义，问题应该需要整合数据推理，不能从题面中判断，可以考虑修改为4月我做了什么运动使我肩颈问题康复，我打算继续做这个运动吗？）
    【主要事件总结】
    {major_events}

    【偏好和习惯变化】
    {preference_changes}
    
    【新养成的习惯】
    {new_habits}
    
    【发生改变的习惯】
    {changed_habits}
    
    **任务要求**
    生成 2-3 个用户可能会向智能助手提出的问题，问题类型包括：
    
    **1. 查询类问题**（询问频率、方式、内容等）
    - 例如："我4月跑步的频率如何？"
    - 例如："10月这段时间我一般怎么通勤上班，为什么？"
    - 例如："9月我喜欢听什么类型的音乐？"
    
    **2. 判断类问题**（比较偏好、评估行为等）
    - 例如："对于1月时间，我更倾向于听古典音乐还是巴洛克音乐？"
    - 例如："2月我是否能做到早睡早起？"
    - 例如："3月我是更喜欢在家做饭还是点外卖？"
    
    **3. 模式识别类问题**（识别用户的习惯模式、行为规律等）
    - 例如："我发现4月份我总是在周几熬夜？"
    - 例如："我在9月时每次压力大就会做什么？"
    - 例如："我的运动习惯在12月有什么规律吗？"
    
    **优秀题目示例**
    1. "我这个月健身的频率怎么样？有没有形成规律？"（查询类 - 频率）
    2. "这段时间我通常选择什么方式上下班？是因为天气原因吗？"（查询类 - 方式 + 原因）
    3. "我这个月养成了什么新习惯？"（查询类 - 新习惯）
    4. "我这个月喜欢上了什么新东西？"（查询类 - 新兴趣）
    5. "相比上个月，我这个月更倾向于喝咖啡还是喝茶？"（判断类 - 偏好比较）
    6. "我这个月在饮食方面是更注重健康还是更随意？"（判断类 - 行为评估）
    7. "我总是在周几熬夜？"（模式识别 - 周期性习惯，需要具体分析数据）
    8. "我每次工作压力大就会减少运动，是这样吗？"（模式识别 - 压力与行为关联，设置错误陷阱真实情况是增加运动）
    
    **设计要点**
    - 使用第一人称"我"来提问
    - 问题应该自然、口语化，像真实用户会问的问题
    - 可以涉及频率、时间、方式、原因、偏好对比等维度
    - 避免过于学术化或分析性的表述
    
    请以 JSON 格式返回问题列表，每个问题包含：
    - question: 问题内容（用户视角的提问）
    - answer: 预期答案（基于提供的数据给出具体回答）
    - analysis: 问题分析（说明基于什么数据设计该问题，需要查询或判断什么信息）
    - question_type: "preference_habit"
    
    返回格式：
    [
        {{
            "question": "问题内容",
            "answer": "预期答案",
            "analysis": "问题分析：基于...数据，需要查询/判断...",
            "question_type": "preference_habit"
        }}
    ]
    """


