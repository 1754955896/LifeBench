def get_temporal_filter_template(questions: list, month_key: str) -> str:
    """
    获取时序问题过滤模板
    
    Args:
        questions: 待过滤的问题列表
        month_key: 月份标识
        
    Returns:
        格式化后的 Prompt
    """
    import json
    questions_json = json.dumps(questions, ensure_ascii=False, indent=2)
    
    return f"""
    作为问题质量评估专家，请评估以下时序相关问题的质量，并选择高质量的问题。
    
    【待评估问题】
    {questions_json}
    
    **评估标准**
    1. **时序性明确**：问题是否清晰涉及时序关系（先后顺序、时间跨度、发展变化等）
    2. **数据可支撑**：提供的事件数据是否足以回答该问题
    3. **难度适中**：问题是否具有一定的挑战性，不是简单的信息查询
    4. **自然真实**：问题是否符合真实用户的提问习惯
    5. **信息适度**：问题是否没有透露过多答案信息
    
    **评分维度**
    - 时序复杂度（0-10）：问题涉及的时序推理难度
    - 数据充分性（0-10）：现有数据能否充分回答问题
    - 问题价值（0-10）：问题的实用性和意义
    
    请以 JSON 格式返回评估结果：
    {{
        "selected_indices": [选中问题的索引列表，如[0, 2, 3]],
        "evaluation_details": [
            {{
                "index": 问题索引,
                "scores": {{
                    "temporal_complexity": 8,
                    "data_sufficiency": 7,
                    "question_value": 9
                }},
                "reason": "选择/排除的理由"
            }}
        ]
    }}
    """


